def parse():
    lines = [l.strip() for l in raw_text.strip().split('\n') if l.strip()]
    sessions = []
    current_session = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r'^(\d{4}/\d{1,2})\s+(.+)$', line)
        if m:
            session_code = m.group(1)
            session_name = line
            current_session = {'code': session_code, 'name': session_name, 'items': []}
            sessions.append(current_session)
            i += 1
            # Skip header if present: No, 語彙 (読み方), 漢字, အဓိပ္ပာယ် (မြန်မာ)
            while i < len(lines) and (lines[i] in ['No', '語彙 (読み方)', '漢字', 'အဓိပ္ပာယ် (မြန်မာ)'] or '語彙' in lines[i]):
                i += 1
            continue
        
        # Check if line is a number
        if line.isdigit() and current_session is not None:
            num = int(line)
            # Next line should be reading, then kanji, then burmese
            if i + 3 < len(lines):
                reading = lines[i+1]
                kanji = lines[i+2]
                burmese = lines[i+3]
                current_session['items'].append({
                    'num': num,
                    'reading': reading,
                    'kanji': kanji,
                    'burmese': burmese
                })
                i += 4
                continue
            else:
                break
        i += 1
    
    print(f"Total sessions parsed: {len(sessions)}")
    total_words = sum(len(s['items']) for s in sessions)
    print(f"Total words parsed: {total_words}")
    for s in sessions:
        print(f"Session {s['code']}: {len(s['items'])} words")

if __name__ == '__main__':
    parse()
